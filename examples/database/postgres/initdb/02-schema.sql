-- The acme shop: every kind of table, column, constraint and index the Postgres catalog describes.
\set ON_ERROR_STOP on

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS postgres_fdw;

CREATE SCHEMA catalog;
COMMENT ON SCHEMA catalog IS 'What the shop sells: categories, products, prices.';
CREATE SCHEMA sales;
COMMENT ON SCHEMA sales IS 'Customers, their orders and what each order holds.';
CREATE SCHEMA billing;
COMMENT ON SCHEMA billing IS 'Invoices and payments of the orders.';
CREATE SCHEMA inventory;
COMMENT ON SCHEMA inventory IS 'Stock in each store and the movements that change it.';
CREATE SCHEMA hr;
COMMENT ON SCHEMA hr IS 'People who work at the shop.';
CREATE SCHEMA audit;
COMMENT ON SCHEMA audit IS 'What changed, when and by whom, written by triggers.';
CREATE SCHEMA staging;
COMMENT ON SCHEMA staging IS 'Raw imports, loose on purpose: no keys, relations only by name.';

-- Types of their own: an enum, a domain with a check, a composite type.
CREATE TYPE sales.order_status AS ENUM ('draft', 'placed', 'paid', 'shipped', 'cancelled');
COMMENT ON TYPE sales.order_status IS 'Where an order is in its life.';
CREATE DOMAIN sales.cpf AS text CHECK (VALUE ~ '^\d{3}\.\d{3}\.\d{3}-\d{2}$');
COMMENT ON DOMAIN sales.cpf IS 'A Brazilian taxpayer number, written 000.000.000-00.';
CREATE DOMAIN catalog.price AS numeric(12, 2) CHECK (VALUE >= 0);
COMMENT ON DOMAIN catalog.price IS 'A price in reais, never negative.';
CREATE TYPE sales.address AS (street text, number text, city text, state char(2), postal_code text);
COMMENT ON TYPE sales.address IS 'A postal address.';

-- An explicit sequence, owned by a column.
CREATE SEQUENCE sales.order_number_seq START 1000;
COMMENT ON SEQUENCE sales.order_number_seq IS 'The numbers printed on the orders.';

CREATE TABLE catalog.categories (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    parent_id integer REFERENCES catalog.categories (id) ON DELETE CASCADE,
    name text NOT NULL,
    slug text NOT NULL UNIQUE
);
COMMENT ON TABLE catalog.categories IS 'Categories of products, as a tree.';
COMMENT ON COLUMN catalog.categories.parent_id IS 'The category above; none at the top.';

CREATE TABLE catalog.products (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sku text NOT NULL,
    name text NOT NULL,
    description text,
    category_id integer NOT NULL REFERENCES catalog.categories (id) ON DELETE RESTRICT,
    price catalog.price NOT NULL,
    cost catalog.price,
    margin numeric(12, 2) GENERATED ALWAYS AS (price - coalesce(cost, 0)) STORED,
    tags text[] NOT NULL DEFAULT '{}',
    attributes jsonb NOT NULL DEFAULT '{}',
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT products_sku_key UNIQUE (sku),
    CONSTRAINT products_cost_below_price CHECK (cost IS NULL OR cost <= price)
);
COMMENT ON TABLE catalog.products IS 'What the shop sells.';
COMMENT ON COLUMN catalog.products.margin IS 'Price minus cost, worked out by the database.';
COMMENT ON COLUMN catalog.products.attributes IS 'Free attributes: colour, size, weight...';
CREATE INDEX products_name_trgm ON catalog.products USING gin (name gin_trgm_ops);
CREATE INDEX products_tags ON catalog.products USING gin (tags);
CREATE INDEX products_active_category ON catalog.products (category_id) WHERE active;
CREATE INDEX products_lower_name ON catalog.products (lower(name));

CREATE TABLE catalog.price_history (
    product_id integer NOT NULL REFERENCES catalog.products (id) ON DELETE CASCADE,
    valid_during tstzrange NOT NULL,
    price catalog.price NOT NULL,
    CONSTRAINT price_history_no_overlap EXCLUDE USING gist (product_id WITH =, valid_during WITH &&)
);
COMMENT ON TABLE catalog.price_history IS 'Every price a product had and when; two periods never overlap.';

CREATE TABLE sales.customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email citext NOT NULL UNIQUE,
    cpf sales.cpf UNIQUE,
    phone text,
    password_hash text NOT NULL,
    birth_date date,
    address sales.address,
    referred_by bigint REFERENCES sales.customers (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE sales.customers IS 'People who buy at the shop.';
COMMENT ON COLUMN sales.customers.password_hash IS 'The password, hashed with bcrypt (pgcrypto).';
COMMENT ON COLUMN sales.customers.referred_by IS 'The customer who brought this one.';

CREATE TABLE hr.employees (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email citext NOT NULL UNIQUE,
    manager_id integer REFERENCES hr.employees (id),
    hired_on date NOT NULL,
    salary numeric(12, 2) CHECK (salary > 0)
);
COMMENT ON TABLE hr.employees IS 'People who work at the shop; each answers to a manager.';
COMMENT ON COLUMN hr.employees.salary IS 'Monthly salary, sensitive.';

CREATE TABLE sales.orders (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    number integer NOT NULL DEFAULT nextval('sales.order_number_seq') UNIQUE,
    customer_id bigint NOT NULL REFERENCES sales.customers (id) ON DELETE RESTRICT,
    sold_by integer REFERENCES hr.employees (id) ON DELETE SET NULL,
    status sales.order_status NOT NULL DEFAULT 'draft',
    placed_at timestamptz,
    shipping_address sales.address,
    total numeric(12, 2) NOT NULL DEFAULT 0,
    CONSTRAINT orders_placed_when_not_draft CHECK (status = 'draft' OR placed_at IS NOT NULL)
);
ALTER SEQUENCE sales.order_number_seq OWNED BY sales.orders.number;
COMMENT ON TABLE sales.orders IS 'An order of a customer.';
COMMENT ON COLUMN sales.orders.total IS 'Sum of the items, kept by a trigger.';
CREATE INDEX orders_customer ON sales.orders (customer_id);
CREATE INDEX orders_open ON sales.orders (placed_at) WHERE status IN ('placed', 'paid');

CREATE TABLE sales.order_items (
    order_id bigint NOT NULL REFERENCES sales.orders (id) ON DELETE CASCADE,
    line smallint NOT NULL,
    product_id integer NOT NULL REFERENCES catalog.products (id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price catalog.price NOT NULL,
    PRIMARY KEY (order_id, line)
);
COMMENT ON TABLE sales.order_items IS 'The lines of an order.';
-- No index on product_id: a foreign key without an index, on purpose.

CREATE TABLE billing.invoices (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES sales.orders (id),
    issued_on date NOT NULL DEFAULT current_date,
    amount numeric(12, 2) NOT NULL,
    access_key char(44) UNIQUE
);
COMMENT ON TABLE billing.invoices IS 'The invoice of an order (one per order).';
COMMENT ON COLUMN billing.invoices.access_key IS 'The 44-digit key of the electronic invoice.';

CREATE TABLE billing.payments (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES billing.invoices (id) ON DELETE CASCADE,
    paid_at timestamptz NOT NULL,
    amount numeric(12, 2) NOT NULL CHECK (amount > 0),
    method text NOT NULL CHECK (method IN ('pix', 'card', 'boleto')),
    card_last4 char(4),
    gateway_payload jsonb
);
COMMENT ON TABLE billing.payments IS 'Money received for an invoice.';

-- A composite foreign key: a refund points at a line of an order.
CREATE TABLE billing.refunds (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    line smallint NOT NULL,
    amount numeric(12, 2) NOT NULL,
    reason text,
    FOREIGN KEY (order_id, line) REFERENCES sales.order_items (order_id, line) ON DELETE CASCADE
);
COMMENT ON TABLE billing.refunds IS 'Money given back for a line of an order.';

CREATE TABLE inventory.stores (
    id smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    region text NOT NULL CHECK (region IN ('north', 'south', 'east', 'west'))
);
COMMENT ON TABLE inventory.stores IS 'Physical stores and their region.';

-- Partitions by range (dates) and by list (region).
CREATE TABLE inventory.movements (
    id bigint GENERATED ALWAYS AS IDENTITY,
    store_id smallint NOT NULL REFERENCES inventory.stores (id),
    product_id integer NOT NULL REFERENCES catalog.products (id),
    moved_at timestamptz NOT NULL,
    quantity integer NOT NULL,
    PRIMARY KEY (id, moved_at)
) PARTITION BY RANGE (moved_at);
COMMENT ON TABLE inventory.movements IS 'Every change of stock, split by year.';
CREATE TABLE inventory.movements_2025 PARTITION OF inventory.movements FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');
CREATE TABLE inventory.movements_2026 PARTITION OF inventory.movements FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE TABLE inventory.movements_other PARTITION OF inventory.movements DEFAULT;

CREATE TABLE inventory.stock (
    store_id smallint NOT NULL,
    region text NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 0,
    PRIMARY KEY (store_id, region, product_id)
) PARTITION BY LIST (region);
COMMENT ON TABLE inventory.stock IS 'How many units of each product each store has, split by region.';
CREATE TABLE inventory.stock_north_south PARTITION OF inventory.stock FOR VALUES IN ('north', 'south');
CREATE TABLE inventory.stock_east_west PARTITION OF inventory.stock FOR VALUES IN ('east', 'west');

-- Inheritance: one log per schema, all children of audit.log.
CREATE TABLE audit.log (
    id bigserial,  -- a serial, not an identity: the children inherit its default
    happened_at timestamptz NOT NULL DEFAULT now(),
    actor text NOT NULL DEFAULT current_user,
    action text NOT NULL,
    row_data jsonb
);
COMMENT ON TABLE audit.log IS 'Every change written by the audit triggers.';
CREATE TABLE audit.sales_log (table_name text NOT NULL) INHERITS (audit.log);
COMMENT ON TABLE audit.sales_log IS 'Changes to the sales schema.';
CREATE TABLE audit.catalog_log (table_name text NOT NULL) INHERITS (audit.log);
COMMENT ON TABLE audit.catalog_log IS 'Changes to the catalog schema.';

-- Staging: no primary key, relations only by name (customer_id, product_id with no foreign key).
CREATE TABLE staging.imported_orders (
    external_ref text,
    customer_id bigint,
    product_id integer,
    quantity integer,
    raw jsonb,
    loaded_at timestamptz DEFAULT now()
);
COMMENT ON TABLE staging.imported_orders IS 'Orders from the marketplace, before they are checked: no key, ids not enforced.';
CREATE UNLOGGED TABLE staging.session_cache (
    token text PRIMARY KEY,
    customer_id bigint,
    expires_at timestamptz NOT NULL
);
COMMENT ON TABLE staging.session_cache IS 'Web sessions (unlogged: lost on a crash).';
