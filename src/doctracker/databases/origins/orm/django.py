"""Read Django apps — their models and their migrations — into the DDL Django's schema editor would send.

Two origins per app, each of its own: the models (`models.py`, or a `models/` package) and the
migrations (`migrations/`, applied in the order of their dependencies). Both become the state of the
app's models, then the DDL its database backend writes (PostgreSQL, MySQL or SQLite, from the settings'
`ENGINE`). From the models: abstract parents' fields copied, multi-table inheritance (`<parent>_ptr`),
proxies (no table), `managed = False` (no table: told as expected), the project's own fields through
their Django base and the defaults their `__init__` sets, the implicit key (`DEFAULT_AUTO_FIELD`, an
`AppConfig.default_auto_field`), `AUTH_USER_MODEL` and Django's own models, many-to-many tables, `Meta`
(`db_table`, `unique_together`, `indexes`, `constraints`, comments), `db_column`, `db_default`,
`GeneratedField`. From the migrations: `CreateModel`, `AddField`, `RemoveField`, `RenameField`,
`AlterField`, `RenameModel`, `DeleteModel`, `AddIndex`, `RemoveIndex`, `AddConstraint`,
`AlterUniqueTogether`, `AlterModelTable`, and `RunSQL` (its SQL read as SQL); `RunPython` is code:
told as not resolved. Names are Django's own (`<table>_<columns>_<md5 digest>` with its suffixes).
Nothing is imported or run.
"""

