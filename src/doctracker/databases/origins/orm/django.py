def _digest(*parts: str) -> str:
    digest = hashlib.md5(usedforsecurity=False)
    for part in parts:
        digest.update(part.encode())
    return digest.hexdigest()[:8]


def index_name(table: str, columns: list[str], suffix: str, limit: int = 63) -> str:
    """The name Django gives an index or constraint (`BaseDatabaseSchemaEditor._create_index_name`)."""
    hashed = f"{_digest(table, *columns)}{suffix}"
    name = f"{table}_{'_'.join(columns)}_{hashed}"
    if len(name) <= limit:
        return name
    if len(hashed) > limit / 3:
        hashed = hashed[:limit // 3]
    other = (limit - len(hashed)) // 2 - 1
    name = f"{table[:other]}_{'_'.join(columns)[:other]}_{hashed}"
    return f"D{name[:-1]}" if name[0] == "_" or name[0].isdigit() else name


# ---------------------------------------------------------------- finding the apps

def _settings(root: Path, project: Project, near: str) -> tuple[str, dict[str, ast.expr]] | None:
    """The project's settings module nearest a folder (`INSTALLED_APPS` and `DATABASES` written in it)."""
    found = []
    for module, file in project.files.items():
        text = _text(root, file)
        if "INSTALLED_APPS" in text and "DATABASES" in text:
            tree = project.tree(module)
            top = {t.id: s.value for s in (tree.body if tree else []) if isinstance(s, ast.Assign) for t in s.targets if isinstance(t, ast.Name)}
            found.append((len(_common_folder(file, near)), module, top))
    if not found:
        return None
    _, module, top = max(found, key=lambda item: item[0])
    return module, top


def _common_folder(a: str, b: str) -> tuple[str, ...]:
    shared = []
    for x, y in zip(Path(a).parent.parts, Path(b).parts):
        if x != y:
            break
        shared.append(x)
    return tuple(shared)


def _text(root: Path, file: str) -> str:
    try:
        return (root / file).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _is_migration(project: Project, module: str) -> bool:
    tree = project.tree(module)
    return any(isinstance(n, ast.ClassDef) and n.name == "Migration" for n in (tree.body if tree else []))


def find(root: Path, files: list[str], project: Project) -> list[dict]:
    """The project's Django origins: per app, its models and its migrations, each an origin.

    Returns:
        Origins as `find_origins` gives them; each also with `app` (its label), and `related` (the
        name of the app's other origin, when both exist).
    """
    apps: dict[str, dict] = {}
    for module, file in sorted(project.files.items()):
        if file not in files:
            continue
        path = Path(file)
        if path.parent.name == "migrations" and re.match(r"\d{4}_", path.name) and "migrations" in _text(root, file) and _is_migration(project, module):
            apps.setdefault(str(path.parent.parent.as_posix()), {}).setdefault("migrations", []).append(file)
        elif (path.name == "models.py" or path.parent.name == "models") and "models" in _text(root, file) \
                and re.search(r"\bmodels\.Model\b|\(\s*\w*Model\s*\)", _text(root, file)):
            folder = path.parent if path.name == "models.py" else path.parent.parent
            apps.setdefault(str(folder.as_posix()), {}).setdefault("models", []).append(file)
    origins = []
    for folder, found in sorted(apps.items()):
        label = _label(root, folder)
        models_name = found["models"][0] if len(found.get("models", [])) == 1 else f"{folder}/models"
        migrations_name = f"{folder}/migrations"
        if found.get("models"):
            origins.append({"name": models_name, "kind": KIND_MODELS, "folder": folder, "app": label,
                            "related": migrations_name if found.get("migrations") else "",
                            "steps": [{"file": f, "version": "", "title": Path(f).name} for f in sorted(found["models"])]})
        if found.get("migrations"):
            origins.append({"name": migrations_name, "kind": KIND_MIGRATIONS, "folder": migrations_name, "app": label,
                            "related": models_name if found.get("models") else "",
                            "steps": [{"file": f, "version": Path(f).stem.split("_", 1)[0], "title": Path(f).stem.split("_", 1)[-1].replace("_", " ")}
                                      for f in _migration_order(project, sorted(found["migrations"]))]})
    return origins


def _label(root: Path, folder: str) -> str:
    """An app's label: its `AppConfig.label`, else its folder's name."""
    match = re.search(r"^\s*label\s*=\s*['\"](\w+)['\"]", _text(root, f"{folder}/apps.py"), re.MULTILINE)
    return match[1] if match else Path(folder).name


def _migration_order(project: Project, files: list[str]) -> list[str]:
    """An app's migrations after the ones each depends on (within the app), else by name."""
    names = {Path(f).stem: f for f in files}
    depends: dict[str, list[str]] = {}
    for stem, file in names.items():
        module = project.module_of(file)
        tree = project.tree(module)
        migration = next((n for n in (tree.body if tree else []) if isinstance(n, ast.ClassDef) and n.name == "Migration"), None)
        value = next((s.value for s in (migration.body if migration else []) if isinstance(s, ast.Assign)
                      and any(getattr(t, "id", "") == "dependencies" for t in s.targets)), None)
        depends[stem] = [ast.literal_eval(e.elts[1]) for e in (value.elts if isinstance(value, ast.List) else [])
                         if isinstance(e, ast.Tuple) and len(e.elts) == 2 and isinstance(e.elts[1], ast.Constant)]
    order, done = [], set()

    def visit(stem: str) -> None:
        if stem in done or stem not in names:
            return
        done.add(stem)
        for before in depends.get(stem, []):
            visit(before)
        order.append(names[stem])
    for stem in sorted(names):
        visit(stem)
    return order


def dialect(root: Path, origin: dict, project: Project) -> tuple[str, str]:
    """The backend of the project's default database (`DATABASES["default"]["ENGINE"]` in its settings);
    else PostgreSQL."""
    found = _settings(root, project, origin["folder"])
    if found:
        module, top = found
        engine = _key(project, module, _key(project, module, top.get("DATABASES"), "default"), "ENGINE")
        if (backend := _ENGINES.get(str(engine or "").rsplit(".", 1)[-1])) is not None:
            return backend, f"ENGINE in {project.files[module]}"
    return "postgres", "no ENGINE written: PostgreSQL"


def _key(project: Project, module: str, node: ast.expr | None, key: str):
    """One key of a dict written in the code (`DATABASES["default"]["ENGINE"]`), its other values left
    unread (a `NAME` from the environment does not hide the `ENGINE`): the node, or a constant's value."""
    if isinstance(node, ast.Name):
        found = project.lookup(module, node.id)
        node = found[1] if found and found[0] == "assign" else None
    if not isinstance(node, ast.Dict):
        return None
    for name, value in zip(node.keys, node.values):
        if isinstance(name, ast.Constant) and name.value == key:
            return value.value if isinstance(value, ast.Constant) else value
    return None


# ---------------------------------------------------------------- reading the state of the models

class _Reader:
    """The state of an app's models (from its models or its migrations), then its DDL."""

    def __init__(self, root: Path, project: Project, origin: dict, backend: str) -> None:
        self.root, self.project, self.origin, self.backend = root, project, origin, backend
        self.app = origin["app"]
        self.models: dict[str, dict] = {}  # lower name → name, fields [(name, field)], options, line, file
        self.unresolved: list[dict] = []
        self.raw: list[dict] = []  # RunSQL, in order
        settings = _settings(root, project, origin["folder"])
        self.settings = settings
        self.auto, self.user = "AutoField", "auth.User"
        if settings:
            module, top = settings
            try:
                if "DEFAULT_AUTO_FIELD" in top:
                    self.auto = str(project.value(top["DEFAULT_AUTO_FIELD"], module)).rsplit(".", 1)[-1]
                if "AUTH_USER_MODEL" in top:
                    self.user = str(project.value(top["AUTH_USER_MODEL"], module))
            except Unresolved:
                pass
        match = re.search(r"default_auto_field\s*=\s*['\"][\w.]*?(\w+)['\"]", _text(root, f"{origin['folder']}/apps.py"))
        if match:
            self.auto = match[1]
        self._others: dict[str, dict] | None = None

    def note(self, file: str, line: int, what: str) -> None:
        self.unresolved.append({"file": file, "line": line, "what": what})

    # ---- a field
    def field(self, call: ast.Call, module: str) -> dict | None:
        """A field call's kind (Django's, for a field of the project's own its Django base) and options."""
        kind = name_of(call.func)
        options = {k.arg: k.value for k in call.keywords if k.arg}
        if kind not in _FIELDS:
            found, where = self.project.class_of(call.func, module)
            seen = 0
            while found is not None and seen < 10:  # the project's field: its base, the defaults its __init__ sets
                seen += 1
                init = next((s for s in found.body if isinstance(s, ast.FunctionDef) and s.name == "__init__"), None)
                for node in ast.walk(init) if init else []:
                    if isinstance(node, ast.Call) and name_of(node.func) == "setdefault" and node.args and isinstance(node.args[0], ast.Constant):
                        options.setdefault(node.args[0].value, node.args[1])
                base = next((b for b in found.bases if name_of(b) in _FIELDS), None)
                if base is not None:
                    kind = name_of(base)
                    break
                found, where = self.project.class_of(found.bases[0], where) if found.bases else (None, "")
            if kind not in _FIELDS:
                return None
        def value(node: ast.expr):
            return self.project.value(node, module)

        field = {"kind": kind}
        for key in ("null", "unique", "primary_key", "max_length", "max_digits", "decimal_places", "db_column", "db_index", "db_comment",
                    "db_table", "db_persist", "parent_link", "related_name"):
            if key in options:
                field[key] = value(options[key])
        if "db_default" in options:
            field["db_default"] = options["db_default"]
            field["module"] = module
        if kind in ("ForeignKey", "OneToOneField", "ManyToManyField"):
            target = call.args[0] if call.args else options.get("to")
            written = ast.unparse(target) if target is not None else ""
            field["to"] = self.user if written.endswith("AUTH_USER_MODEL") else (value(target) if isinstance(target, ast.Constant) else name_of(target))
            if "to_field" in options:
                field["to_field"] = value(options["to_field"])
        if kind == "CompositePrimaryKey":
            field["fields"] = [value(a) for a in call.args]
            field["primary_key"] = True
        if kind == "GeneratedField":
            field["expression"] = self.expression(options["expression"])
            field["output"] = self.field(options["output_field"], module)
        return field

    def expression(self, node: ast.expr) -> str:
        """A database expression (`F("a") * F("b")`, `CombinedExpression(...)`) as Django writes it."""
        if isinstance(node, ast.Call) and name_of(node.func) == "F":
            return f'"{node.args[0].value}"'
        if isinstance(node, ast.BinOp):
            operator = {ast.Mult: "*", ast.Add: "+", ast.Sub: "-", ast.Div: "/"}[type(node.op)]
            return f"({self.expression(node.left)} {operator} {self.expression(node.right)})"
        if isinstance(node, ast.Call) and name_of(node.func) == "CombinedExpression":
            return f"({self.expression(node.args[0])} {node.args[1].value} {self.expression(node.args[2])})"
        if isinstance(node, ast.Call) and name_of(node.func) == "Value":
            return repr(ast.literal_eval(node.args[0]))
        if isinstance(node, ast.Constant):
            return repr(node.value)
        raise Unresolved(f"the expression {ast.unparse(node)[:60]}", getattr(node, "lineno", 0))

    def condition(self, node: ast.expr, module: str) -> str:
        """A `Q(...)` as Django writes it in a check or a partial index."""
        pairs = [(k.arg, self.project.value(k.value, module)) for k in node.keywords if k.arg] \
            + [tuple(self.project.value(a, module)) for a in node.args if isinstance(a, (ast.Tuple, ast.List))]
        parts = []
        for key, value in pairs:
            column, lookup = key.rsplit("__", 1) if "__" in key and key.rsplit("__", 1)[1] in (*_LOOKUPS, "in", "isnull") else (key, "exact")
            quoted = f'"{column}"'
            if lookup == "in":
                parts.append(f"{quoted} IN ({', '.join(_literal(v) for v in value)})")
            elif lookup == "isnull":
                parts.append(f"{quoted} IS {'NULL' if value else 'NOT NULL'}")
            else:
                parts.append(f"{quoted} {_LOOKUPS[lookup]} {_literal(value)}")
        return " AND ".join(parts)

    def options(self, meta: dict[str, ast.expr], module: str, file: str) -> dict:
        found = {}
        for key, node in meta.items():
            try:
                if key in ("db_table", "abstract", "proxy", "managed", "db_table_comment"):
                    found[key] = self.project.value(node, module)
                elif key == "unique_together":
                    value = self.project.value(node, module)
                    found[key] = [list(v) for v in value] if value and isinstance(value[0], (list, tuple)) else [list(value)] if value else []
                elif key == "indexes":
                    found[key] = [{"name": self.project.value(keyword(i, "name"), module), "fields": self.project.value(keyword(i, "fields"), module),
                                   "condition": self.condition(keyword(i, "condition"), module) if keyword(i, "condition") else None}
                                  for i in node.elts]
                elif key == "constraints":
                    found[key] = [self.constraint(c, module) for c in node.elts]
            except (Unresolved, AttributeError, TypeError) as problem:
                self.note(file, getattr(node, "lineno", 0), f"Meta.{key}: {getattr(problem, 'what', problem)}")
        return found

    def constraint(self, node: ast.Call, module: str) -> dict:
        kind = name_of(node.func)
        name = self.project.value(keyword(node, "name"), module)
        if kind == "CheckConstraint":
            condition = keyword(node, "condition") or keyword(node, "check")
            return {"kind": "check", "name": name, "check": self.condition(condition, module)}
        if kind == "UniqueConstraint":
            return {"kind": "unique", "name": name, "fields": self.project.value(keyword(node, "fields"), module) or [],
                    "condition": self.condition(keyword(node, "condition"), module) if keyword(node, "condition") else None}
        raise Unresolved(f"the constraint {kind}", node.lineno)

    def read_models(self) -> "_Reader":
        """The state from the app's models."""
        for step in self.origin["steps"]:
            module = self.project.module_of(step["file"])
            self._models_of(module, step["file"], self.models)
        return self

    def _models_of(self, module: str, file: str, into: dict) -> None:
        tree = self.project.tree(module)
        for node in tree.body if tree else []:
            if not isinstance(node, ast.ClassDef):
                continue
            bases = [name_of(b) for b in node.bases]
            if not any(b == "Model" or b.lower() in into for b in bases):
                continue
            meta_node = next((s for s in node.body if isinstance(s, ast.ClassDef) and s.name == "Meta"), None)
            meta = {t.id: s.value for s in (meta_node.body if meta_node else []) if isinstance(s, ast.Assign) for t in s.targets if isinstance(t, ast.Name)}
            options = self.options(meta, module, file)
            fields: list[tuple[str, dict]] = []
            parent = None
            for base in bases:
                known = into.get(base.lower())
                if known and known["options"].get("abstract"):
                    fields += [(n, dict(f)) for n, f in known["fields"]]
                    for key in ("unique_together", "indexes", "constraints"):
                        if key in known["options"] and key not in options:
                            options[key] = known["options"][key]
                elif known:
                    parent = known
            own = []
            for statement in node.body:
                if isinstance(statement, ast.Assign) and isinstance(statement.value, ast.Call) and isinstance(statement.targets[0], ast.Name):
                    try:
                        field = self.field(statement.value, module)
                    except Unresolved as problem:
                        self.note(file, statement.lineno, f"{node.name}.{statement.targets[0].id}: {problem.what}")
                        continue
                    if field is not None:
                        own.append((statement.targets[0].id, {**field, "line": statement.lineno}))
            for _, field in own:  # ForeignKey("self"): the model itself
                if field.get("to") == "self":
                    field["to"] = node.name
            if options.get("proxy"):
                continue
            if parent is not None:  # multi-table inheritance: a key to the parent's table, first
                fields.insert(0, (f"{parent['name'].lower()}_ptr", {"kind": "OneToOneField", "to": parent["name"], "primary_key": True,
                                                                     "parent_link": True, "line": node.lineno}))
            # makemigrations writes a new model's relation fields after the others
            fields += [f for f in own if f[1]["kind"] not in ("ForeignKey", "OneToOneField", "ManyToManyField") or f[1].get("parent_link")]
            fields += [f for f in own if f[1]["kind"] in ("ForeignKey", "OneToOneField", "ManyToManyField") and not f[1].get("parent_link")]
            if not options.get("abstract") and not any(f.get("primary_key") for _, f in fields):
                fields.insert(0, ("id", {"kind": self.auto, "primary_key": True, "line": node.lineno}))
            into[node.name.lower()] = {"name": node.name, "fields": fields, "options": options, "line": node.lineno, "file": file}

    def read_migrations(self) -> "_Reader":
        """The state from the app's migrations, operation after operation."""
        for step in self.origin["steps"]:
            module = self.project.module_of(step["file"])
            tree = self.project.tree(module)
            for node in ast.walk(tree) if tree else []:
                if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and name_of(node.func.value) == "migrations":
                    try:
                        self._operation(node, module, step["file"])
                    except (Unresolved, KeyError, AttributeError, TypeError, IndexError) as problem:
                        self.note(step["file"], node.lineno, f"migrations.{node.func.attr}: {getattr(problem, 'what', problem)}")
        return self

    def _operation(self, node: ast.Call, module: str, file: str) -> None:
        kind, given = node.func.attr, {k.arg: k.value for k in node.keywords if k.arg}
        def value(node: ast.expr):
            return self.project.value(node, module)

        def model(key: str) -> dict:
            return self.models[value(given[key]).lower()]

        if kind == "CreateModel":
            options = self.options({value(k): v for k, v in zip(given["options"].keys, given["options"].values)}, module, file) if "options" in given else {}
            if options.get("proxy"):
                return
            fields = []
            for item in given["fields"].elts:
                field = self.field(item.elts[1], module)
                if field is not None:
                    fields.append((value(item.elts[0]), {**field, "line": item.lineno}))
            self.models[value(given["name"]).lower()] = {"name": value(given["name"]), "fields": fields, "options": options, "line": node.lineno, "file": file}
        elif kind == "DeleteModel":
            self.models.pop(value(given["name"]).lower(), None)
        elif kind == "RenameModel":
            found = self.models.pop(value(given["old_name"]).lower())
            found["name"] = value(given["new_name"])
            self.models[found["name"].lower()] = found
        elif kind == "AlterModelTable":
            model("name")["options"]["db_table"] = value(given["table"])
        elif kind in ("AddField", "AlterField"):
            field = self.field(given["field"], module)
            found = model("model_name")
            name = value(given["name"])
            found["fields"] = [f for f in found["fields"] if f[0] != name] if kind == "AlterField" else found["fields"]
            if field is not None:
                found["fields"].append((name, {**field, "line": node.lineno}))
        elif kind == "RemoveField":
            found = model("model_name")
            found["fields"] = [f for f in found["fields"] if f[0] != value(given["name"])]
        elif kind == "RenameField":
            found = model("model_name")
            found["fields"] = [(value(given["new_name"]) if n == value(given["old_name"]) else n, f) for n, f in found["fields"]]
        elif kind == "AddIndex":
            index = given["index"]
            model("model_name")["options"].setdefault("indexes", []).append(
                {"name": value(keyword(index, "name")), "fields": value(keyword(index, "fields")),
                 "condition": self.condition(keyword(index, "condition"), module) if keyword(index, "condition") else None})
        elif kind == "RemoveIndex":
            found = model("model_name")
            found["options"]["indexes"] = [i for i in found["options"].get("indexes", []) if i["name"] != value(given["name"])]
        elif kind == "AddConstraint":
            model("model_name")["options"].setdefault("constraints", []).append(self.constraint(given["constraint"], module))
        elif kind == "RemoveConstraint":
            found = model("model_name")
            found["options"]["constraints"] = [c for c in found["options"].get("constraints", []) if c["name"] != value(given["name"])]
        elif kind == "AlterUniqueTogether":
            together = given["unique_together"]
            model("name")["options"]["unique_together"] = [value(e) for e in together.elts] if isinstance(together, (ast.Set, ast.List, ast.Tuple)) else []
        elif kind == "RunSQL":
            sql = node.args[0] if node.args else given["sql"]
            text = value(sql)
            for item in text if isinstance(text, list) else [text]:
                self.raw.append({"file": file, "line": node.lineno, "text": item if isinstance(item, str) else item[0]})
        elif kind == "RunPython":
            self.note(file, node.lineno, "RunPython (Python code: what it does is only known when it runs)")
        elif kind not in ("swappable_dependency", "Migration", "AlterModelOptions", "AlterModelManagers", "SeparateDatabaseAndState"):
            self.note(file, node.lineno, f"migrations.{kind}")

    # ---- the DDL
    def _table(self, model: dict) -> str:
        return model["options"].get("db_table") or f"{self.app}_{model['name'].lower()}"

    def _other_apps(self) -> dict[str, dict]:
        """The models of the project's other apps, from their models files (for keys pointing to them)."""
        if self._others is None:
            self._others = {}
            for module, file in self.project.files.items():
                if Path(file).name == "models.py" and Path(file).parent.as_posix() != self.origin["folder"]:
                    found: dict = {}
                    label = _label(self.root, str(Path(file).parent.as_posix()))
                    saved, self.app = self.app, label
                    try:
                        self._models_of(module, file, found)
                    finally:
                        self.app = saved
                    for key, model in found.items():
                        self._others[f"{label}.{key}"] = {**model, "app": label}
        return self._others

    def target(self, to: str) -> tuple[str, str, str]:
        """The table, key column and key field kind a relation points to."""
        key = to.lower() if "." in to else f"{self.app}.{to.lower()}"
        if key in _BUILTIN:
            return _BUILTIN[key]
        if key.split(".", 1)[0] == self.app.lower() and key.split(".", 1)[1] in self.models:
            model, app = self.models[key.split(".", 1)[1]], self.app
        elif key in self._other_apps():
            model, app = self._other_apps()[key], self._other_apps()[key]["app"]
        else:
            raise Unresolved(f"the model {to}")
        name, field = next((n, f) for n, f in model["fields"] if f.get("primary_key") and f["kind"] != "CompositePrimaryKey")
        table = model["options"].get("db_table") or f"{app}_{model['name'].lower()}"
        if field["kind"] in ("ForeignKey", "OneToOneField"):
            return table, f"{name}_id", self.target(field["to"])[2]
        return table, field.get("db_column") or name, field["kind"]

    def _column_type(self, field: dict) -> str:
        kind = field["kind"]
        written = _TYPES[self.backend].get(kind)
        if written is None:
            raise Unresolved(f"the field {kind}")
        if kind == "DecimalField" and "%s" in written:
            return written % (field.get("max_digits"), field.get("decimal_places"))
        if "%s" in written:
            length = field.get("max_length", _LENGTHS.get(kind))
            return written % length if length is not None else written.replace("(%s)", "")
        return written

    def _quote(self, name: str) -> str:
        return f"`{name}`" if self.backend == "mysql" else f'"{name}"'

    def ddl(self) -> tuple[list[dict], list[dict]]:
        """The statements creating the app's tables as its backend writes them, and the tables it expects
        but does not create (`managed = False`)."""
        statements, deferred, expects = [], [], []
        q = self._quote
        for model in self.models.values():
            options = model["options"]
            if options.get("abstract") or options.get("proxy"):
                continue
            table = self._table(model)
            place = {"file": model["file"], "line": model["line"]}
            if options.get("managed") is False:
                expects.append({"table": table, **place})
                continue
            parts, columns = [], {}
            composite = next((f["fields"] for _, f in model["fields"] if f["kind"] == "CompositePrimaryKey"), None)
            for name, field in model["fields"]:
                kind = field["kind"]
                where = {"file": model["file"], "line": field.get("line", model["line"])}
                try:
                    if kind == "CompositePrimaryKey":
                        continue
                    if kind == "ManyToManyField":
                        deferred += self._many_to_many(model, table, name, field, where)
                        continue
                    if kind in ("ForeignKey", "OneToOneField"):
                        to_table, to_column, to_kind = self.target(field["to"])
                        column = field.get("db_column") or f"{name}_id"
                        columns[name] = column
                        typ = self._column_type({"kind": _RELATED.get(to_kind, to_kind)})
                        part = f"{q(column)} {typ} {'NULL' if field.get('null') else 'NOT NULL'}"
                        if field.get("primary_key"):
                            part += " PRIMARY KEY"
                        elif kind == "OneToOneField" or field.get("unique"):
                            part += " UNIQUE"
                        if self.backend == "sqlite":
                            part += f" REFERENCES {q(to_table)} ({q(to_column)}) DEFERRABLE INITIALLY DEFERRED"
                        else:
                            fk = index_name(table, [column], f"_fk_{to_table}_{to_column}", 64 if self.backend == "mysql" else 63)
                            deferred.append({**where, "text": f"ALTER TABLE {q(table)} ADD CONSTRAINT {q(fk)} FOREIGN KEY ({q(column)}) "
                                                              f"REFERENCES {q(to_table)} ({q(to_column)})"
                                                              + (" DEFERRABLE INITIALLY DEFERRED" if self.backend == "postgres" else "")})
                        indexed = field.get("db_index", True) and not field.get("primary_key") and not (kind == "OneToOneField" or field.get("unique"))
                        if indexed and self.backend != "mysql":  # MySQL indexes a foreign key by itself
                            deferred.append({**where, "text": f"CREATE INDEX {q(index_name(table, [column], ''))} ON {q(table)} ({q(column)})"})
                        parts.append(part)
                        continue
                    column = field.get("db_column") or name
                    columns[name] = column
                    if kind == "GeneratedField":
                        output = self._column_type(field["output"])
                        expression = field["expression"]
                        if self.backend == "sqlite" and field["output"]["kind"] == "DecimalField":  # SQLite's cast of a decimal
                            expression = f"(CAST({expression} AS NUMERIC))"
                        parts.append(f"{q(column)} {output} GENERATED ALWAYS AS ({expression})" + (" STORED" if field.get("db_persist") else " VIRTUAL"))
                        continue
                    typ = self._column_type(field)
                    if kind in _AUTO:
                        if self.backend == "sqlite":
                            parts.append(f"{q(column)} integer NOT NULL PRIMARY KEY AUTOINCREMENT")
                        else:
                            parts.append(f"{q(column)} {typ} NOT NULL PRIMARY KEY {_AUTO_SUFFIX[self.backend]}")
                        continue
                    part = f"{q(column)} {typ}"
                    if field.get("db_default") is not None:
                        part += f" DEFAULT ({self._db_default(field)})"
                    part += " NULL" if field.get("null") else " NOT NULL"
                    if field.get("primary_key"):
                        part += " PRIMARY KEY"
                    elif field.get("unique"):
                        part += " UNIQUE"
                    if kind in _POSITIVE and self.backend != "mysql":
                        part += f' CHECK ("{column}" >= 0)'
                    if field.get("db_comment") and self.backend == "mysql":
                        part += " COMMENT '" + str(field["db_comment"]).replace("'", "''") + "'"
                    parts.append(part)
                    if self.backend == "postgres" and (field.get("unique") or field.get("db_index") or field.get("primary_key")) \
                            and (typ == "text" or typ.startswith("varchar")):
                        ops = "varchar_pattern_ops" if typ.startswith("varchar") else "text_pattern_ops"
                        deferred.append({**where, "text": f"CREATE INDEX {q(index_name(table, [column], '_like'))} ON {q(table)} ({q(column)} {ops})"})
                    if field.get("db_index") and not field.get("unique") and not field.get("primary_key"):
                        deferred.append({**where, "text": f"CREATE INDEX {q(index_name(table, [column], ''))} ON {q(table)} ({q(column)})"})
                    if field.get("db_comment") and self.backend == "postgres":
                        deferred.append({**where, "text": f"COMMENT ON COLUMN {q(table)}.{q(column)} IS '" + str(field["db_comment"]).replace("'", "''") + "'"})
                except Unresolved as problem:
                    self.note(where["file"], where["line"], f"{model['name']}.{name}: {problem.what}")
            if composite:
                parts.append(f"PRIMARY KEY ({', '.join(q(columns.get(c, c)) for c in composite)})")
            for constraint in options.get("constraints", []):
                if constraint["kind"] == "check":
                    check = constraint["check"]
                    if self.backend == "sqlite":  # SQLite gets a decimal's value as a string
                        for name, field in model["fields"]:
                            if field["kind"] == "DecimalField":
                                column = columns.get(name, name)
                                check = re.sub(rf'("{re.escape(column)}" (?:>=|<=|>|<|=) )(-?\d+(?:\.\d+)?)\b', r"\1'\2'", check)
                    parts.append(f"CONSTRAINT {q(constraint['name'])} CHECK ({check})")
                elif not constraint.get("condition"):
                    cols = [columns.get(f, f) for f in constraint["fields"]]
                    parts.append(f"CONSTRAINT {q(constraint['name'])} UNIQUE ({', '.join(q(c) for c in cols)})")
                else:
                    cols = [columns.get(f, f) for f in constraint["fields"]]
                    deferred.append({**place, "text": f"CREATE UNIQUE INDEX {q(constraint['name'])} ON {q(table)} ({', '.join(q(c) for c in cols)}) WHERE {constraint['condition']}"})
            create = f"CREATE TABLE {q(table)} ({', '.join(parts)})"
            if options.get("db_table_comment") and self.backend == "mysql":
                create += " COMMENT = '" + str(options["db_table_comment"]).replace("'", "''") + "'"
            statements.append({**place, "text": create})
            if options.get("db_table_comment") and self.backend == "postgres":
                statements.append({**place, "text": f"COMMENT ON TABLE {q(table)} IS '" + str(options["db_table_comment"]).replace("'", "''") + "'"})
            for together in options.get("unique_together", []):
                cols = [columns.get(f, f) for f in together]
                name = index_name(table, cols, "_uniq", 64 if self.backend == "mysql" else 63)
                text = f"CREATE UNIQUE INDEX {q(name)} ON {q(table)} ({', '.join(q(c) for c in cols)})" if self.backend == "sqlite" \
                    else f"ALTER TABLE {q(table)} ADD CONSTRAINT {q(name)} UNIQUE ({', '.join(q(c) for c in cols)})"
                deferred.append({**place, "text": text})
            for index in options.get("indexes", []):
                cols = [columns.get(f.lstrip("-"), f.lstrip("-")) for f in index["fields"]]
                deferred.append({**place, "text": f"CREATE INDEX {q(index['name'])} ON {q(table)} ({', '.join(q(c) for c in cols)})"
                                                  + (f" WHERE {index['condition']}" if index["condition"] else "")})
        return statements + deferred + self.raw, expects

    def _db_default(self, field: dict) -> str:
        node = field["db_default"]
        if isinstance(node, ast.Call) and name_of(node.func) == "Now":
            return _NOW[self.backend]
        return _literal(self.project.value(node, field["module"]))

    def _many_to_many(self, model: dict, table: str, name: str, field: dict, where: dict) -> list[dict]:
        """The table joining a many-to-many field's two sides (Django's automatic `through`)."""
        q = self._quote
        to_table, to_column, to_kind = self.target(field["to"])
        mine_table, mine_column, mine_kind = self.target(model["name"])
        other = field["to"].split(".")[-1].lower()
        mine = model["name"].lower()
        if other == mine:
            mine, other = f"from_{mine}", f"to_{other}"
        through = field.get("db_table") or f"{table}_{name}"
        a, b = f"{mine}_id", f"{other}_id"
        def rel(kind: str) -> str:
            return self._column_type({"kind": _RELATED.get(kind, kind)})

        identity = f'{q("id")} integer NOT NULL PRIMARY KEY AUTOINCREMENT' if self.backend == "sqlite" \
            else f"{q('id')} {self._column_type({'kind': self.auto})} NOT NULL PRIMARY KEY {_AUTO_SUFFIX[self.backend]}"
        if self.backend == "sqlite":
            create = (f"CREATE TABLE {q(through)} ({identity}, {q(a)} {rel(mine_kind)} NOT NULL REFERENCES {q(mine_table)} ({q(mine_column)}) "
                      f"DEFERRABLE INITIALLY DEFERRED, {q(b)} {rel(to_kind)} NOT NULL REFERENCES {q(to_table)} ({q(to_column)}) DEFERRABLE INITIALLY DEFERRED)")
            statements = [{**where, "text": create},
                          {**where, "text": f"CREATE UNIQUE INDEX {q(index_name(through, [a, b], '_uniq'))} ON {q(through)} ({q(a)}, {q(b)})"}]
        else:
            statements = [{**where, "text": f"CREATE TABLE {q(through)} ({identity}, {q(a)} {rel(mine_kind)} NOT NULL, {q(b)} {rel(to_kind)} NOT NULL)"},
                          {**where, "text": f"ALTER TABLE {q(through)} ADD CONSTRAINT {q(index_name(through, [a, b], '_uniq'))} UNIQUE ({q(a)}, {q(b)})"}]
            for column, target_table, target_column in ((a, mine_table, mine_column), (b, to_table, to_column)):
                fk = index_name(through, [column], f"_fk_{target_table}_{target_column}")
                statements.append({**where, "text": f"ALTER TABLE {q(through)} ADD CONSTRAINT {q(fk)} FOREIGN KEY ({q(column)}) REFERENCES "
                                                    f"{q(target_table)} ({q(target_column)})" + (" DEFERRABLE INITIALLY DEFERRED" if self.backend == "postgres" else "")})
        if self.backend != "mysql":
            statements += [{**where, "text": f"CREATE INDEX {q(index_name(through, [a], ''))} ON {q(through)} ({q(a)})"},
                           {**where, "text": f"CREATE INDEX {q(index_name(through, [b], ''))} ON {q(through)} ({q(b)})"}]
        return statements

    def mapping(self) -> list[dict]:
        """Each model class ↔ its table, each field ↔ its column (models origins only)."""
        found = []
        for model in self.models.values():
            if model["options"].get("abstract") or model["options"].get("proxy"):
                continue
            columns = {n: f.get("db_column") or (f"{n}_id" if f["kind"] in ("ForeignKey", "OneToOneField") else n)
                       for n, f in model["fields"] if f["kind"] not in ("ManyToManyField", "CompositePrimaryKey")}
            found.append({"class": f"{self.project.module_of(model['file'])}.{model['name']}", "table": self._table(model),
                          "file": model["file"], "line": model["line"], "columns": columns})
        return found


def _literal(value) -> str:
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def read(root: Path, origin: dict, dialect_name: str, project: Project) -> dict:
    """Read a Django origin (an app's models or its migrations).

    Returns:
        `statements` (`file`, `line`, `text`), `unresolved`, `expects` (the `managed = False` tables) and
        `mapping` (class ↔ table; models origins only).
    """
    reader = _Reader(root, project, origin, dialect_name if dialect_name in _TYPES else "postgres")
    if origin["kind"] == KIND_MODELS:
        reader.read_models()
    else:
        reader.read_migrations()
    statements, expects = reader.ddl()
    return {"statements": statements, "unresolved": reader.unresolved, "expects": expects,
            "mapping": reader.mapping() if origin["kind"] == KIND_MODELS else []}


